"""Write lit tests and result.json for fill-line."""

from __future__ import annotations

import json
from datetime import datetime, timezone
from pathlib import Path

from fill_line_agent.oracle import RunResult, TargetLine


def _shell_join(argv: list[str]) -> str:
    parts: list[str] = []
    for arg in argv:
        if any(c.isspace() for c in arg) or any(c in arg for c in "\"'"):
            parts.append("'" + arg.replace("'", "'\\''") + "'")
        else:
            parts.append(arg)
    return " ".join(parts)


def command_line(result: RunResult) -> str:
    """Human-readable tool invocation using the tool name, not an absolute path."""
    args = _shell_join(result.argv)
    return f"{result.tool} {args} input.{result.fmt} -o output.{result.fmt}".rstrip()


def render_test(
    result: RunResult,
    target: TargetLine,
    *,
    attempt: int | None = None,
    filename: str | None = None,
    testing: str | None = None,
) -> tuple[str, str]:
    """Return ``(filename, file_contents)`` for an accepted or attempt candidate."""
    comment = ";" if result.fmt == "ll" else "#"
    args = _shell_join(result.argv)
    run_line = f"{comment} RUN: {result.tool} {args} %s -o /dev/null".rstrip()
    if attempt is None:
        header = [
            f"{comment} Autogenerated by fill-line for {target}",
            f"{comment} Generated: {datetime.now(timezone.utc).isoformat()}",
            run_line,
            "",
        ]
        name = filename or f"test.{result.fmt}"
    else:
        m = result.measure
        if m is not None:
            outcome = (
                f"exit={result.exit_code} target={m.status} {m.n_hit}/{m.n_points} "
                f"fn={m.function_n_hit}/{m.function_n_points} "
                f"changed={str(result.changed).lower()}"
            )
        else:
            outcome = (
                f"exit={result.exit_code} timed_out={str(result.timed_out).lower()} "
                f"changed={str(result.changed).lower()}"
            )
        header = [
            f"{comment} Attempt {attempt} by fill-line for {target}",
            f"{comment} Outcome: {outcome}",
        ]
        if testing:
            header.append(f"{comment} Testing: {testing}")
        header.extend(
            [
                f"{comment} Command: {command_line(result)}",
                run_line,
                "",
            ]
        )
        name = filename or f"run_{attempt:03d}.{result.fmt}"
    body = result.input_text
    if body and not body.endswith("\n"):
        body += "\n"
    return name, "\n".join(header) + body


def write_attempt(
    out_dir: Path,
    *,
    result: RunResult,
    target: TargetLine,
    attempt: int,
    testing: str | None = None,
) -> str:
    """Write ``attempts/run_NNN.<fmt>`` and return the relative path string."""
    attempts = out_dir / "attempts"
    attempts.mkdir(parents=True, exist_ok=True)
    name, text = render_test(
        result, target, attempt=attempt, testing=testing
    )
    path = attempts / name
    path.write_text(text, encoding="utf-8")
    return f"attempts/{name}"


def write_analysis(out_dir: Path, analyses: list[dict]) -> Path:
    """Write ``analysis.json`` with every analysis so far; the last is current."""
    out_dir.mkdir(parents=True, exist_ok=True)
    path = out_dir / "analysis.json"
    payload = {"latest": analyses[-1] if analyses else None, "all": analyses}
    path.write_text(json.dumps(payload, indent=2) + "\n", encoding="utf-8")
    return path


def write_outputs(
    out_dir: Path,
    *,
    target: TargetLine,
    status: str,
    result: RunResult | None,
    history: list[dict],
    extra: dict | None = None,
) -> Path | None:
    """Write result.json and optionally the lit test. Return the test path."""
    out_dir.mkdir(parents=True, exist_ok=True)
    test_path: Path | None = None
    payload: dict = {
        "status": status,
        "target": str(target),
        "history": history,
    }
    if extra:
        payload.update(extra)
    if result is not None:
        name, text = render_test(result, target)
        test_path = out_dir / name
        test_path.write_text(text, encoding="utf-8")
        payload["format"] = result.fmt
        payload["tool"] = result.tool
        payload["argv"] = result.argv
        payload["output_changed"] = result.changed
        payload["test"] = name
    (out_dir / "result.json").write_text(
        json.dumps(payload, indent=2) + "\n",
        encoding="utf-8",
    )
    return test_path
