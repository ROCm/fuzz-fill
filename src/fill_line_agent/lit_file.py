"""Parse and compare LLVM lit test files for fill-line / usher-test."""

from __future__ import annotations

import difflib
import re
import shlex
from dataclasses import dataclass, field
from pathlib import Path
from typing import Literal

ToolName = Literal["opt", "llc"]
InputFormat = Literal["ll", "mir"]
# Where the RUN directed tool output (stripped from argv for coverage).
# stdout: ``-o -``; null: ``-o /dev/null``; default: no -o / other.
OutputDest = Literal["stdout", "null", "default"]
RunShape = Literal["llc_codegen", "llc_partial", "mir_pass", "opt", "other"]

_RUN_START = re.compile(r"^[;#]\s*RUN:\s*(.*)$")
_IF_WRAP = re.compile(r"^%if\s+\S+\s+%\{\s*(.*?)\s*%\}\s*$")
_NOTE_RE = re.compile(
    r"^[;#]\s*NOTE:\s*Assertions have been autogenerated by\s+(\S+)",
    re.MULTILINE,
)
_DEFINE_RE = re.compile(
    r"^(define\b[^\n]*?@([A-Za-z0-9_.$]+)\s*\([^)]*\)[^{]*\{)",
    re.MULTILINE,
)
_CHECK_LINE = re.compile(r"^[;#]\s*(?:CHECK(?:-[A-Z0-9_]+)*):")


@dataclass
class ParsedRun:
    """One supported ``RUN:`` line from a lit test."""

    raw: str
    tool: ToolName
    argv: list[str]
    stdin_redirect: bool  # True if ``< %s``, False if ``%s`` as positional
    redirect_stderr: bool  # ``2>&1`` before FileCheck
    filecheck_args: list[str] | None  # None => no FileCheck pipe
    line_index: int  # 0-based among joined RUN lines
    output: OutputDest = "default"


@dataclass
class LitFunction:
    """One LLVM IR function and the CHECK lines immediately above it."""

    name: str
    start: int  # 0-based line of first CHECK or define
    define_line: int  # 0-based line of ``define``
    end: int  # exclusive end line
    check_lines: list[str] = field(default_factory=list)
    body_lines: list[str] = field(default_factory=list)


@dataclass
class PolicyDiffResult:
    ok: bool
    reason: str | None = None
    changed_functions: list[str] = field(default_factory=list)
    run_lines_changed: bool = False
    other_changes: list[str] = field(default_factory=list)


def join_run_lines(text: str) -> list[tuple[int, str]]:
    """Return ``(start_line_1based, joined_body)`` for each RUN directive."""
    lines = text.splitlines()
    out: list[tuple[int, str]] = []
    i = 0
    while i < len(lines):
        m = _RUN_START.match(lines[i])
        if not m:
            i += 1
            continue
        start = i + 1
        body = m.group(1).rstrip()
        while body.endswith("\\"):
            body = body[:-1].rstrip() + " "
            i += 1
            if i >= len(lines):
                break
            cont = re.sub(r"^[;#]\s*", "", lines[i]).strip()
            body += cont
        out.append((start, body.strip()))
        i += 1
    return out


def parse_run_body(body: str, *, line_index: int = 0) -> ParsedRun | None:
    """Parse a joined RUN body into a supported shape, or ``None`` if unsupported."""
    raw = body.strip()
    if not raw:
        return None
    # Reject unsupported constructs early.
    lower = raw.lower()
    if re.search(r"(^|\s)not(\s|$)", raw):
        return None
    if "split-file" in lower or "%t" in raw or "%T" in raw:
        return None
    if re.search(r"(^|\s)sed(\s|$)", raw):
        return None
    if raw.count("|") > 1:
        return None

    filecheck_args: list[str] | None = None
    tool_part = raw
    if "|" in raw:
        left, right = raw.split("|", 1)
        tool_part = left.strip()
        fc_tokens = shlex.split(right.strip())
        if not fc_tokens or fc_tokens[0] != "FileCheck":
            return None
        # Expect FileCheck [args...] %s
        if "%s" not in fc_tokens:
            return None
        fc_tokens = [t for t in fc_tokens if t != "%s"]
        if fc_tokens[0] != "FileCheck":
            return None
        filecheck_args = fc_tokens[1:]

    redirect_stderr = False
    if "2>&1" in tool_part:
        redirect_stderr = True
        tool_part = tool_part.replace("2>&1", " ")

    tokens = shlex.split(tool_part)
    if not tokens:
        return None
    tool = tokens[0]
    if tool not in ("opt", "llc"):
        return None

    stdin_redirect = False
    output: OutputDest = "default"
    argv: list[str] = []
    i = 1
    while i < len(tokens):
        tok = tokens[i]
        if tok == "%s":
            i += 1
            continue
        if tok == "<":
            if i + 1 < len(tokens) and tokens[i + 1] == "%s":
                stdin_redirect = True
                i += 2
                continue
            return None
        if tok in ("-o", "--o") and i + 1 < len(tokens) and tokens[i + 1] in ("-", "/dev/null"):
            output = "stdout" if tokens[i + 1] == "-" else "null"
            i += 2
            continue
        if tok.startswith("-o=") and tok.split("=", 1)[1] in ("-", "/dev/null"):
            dest = tok.split("=", 1)[1]
            output = "stdout" if dest == "-" else "null"
            i += 1
            continue
        if tok == "/dev/null":
            i += 1
            continue
        if tok.startswith("%"):
            return None
        argv.append(tok)
        i += 1

    if "%s" not in raw and "< %s" not in raw and "<%s" not in raw.replace(" ", ""):
        # Must reference the test file somehow.
        if not stdin_redirect and "%s" not in tokens:
            return None

    return ParsedRun(
        raw=raw,
        tool=tool,  # type: ignore[arg-type]
        argv=argv,
        stdin_redirect=stdin_redirect or ("< %s" in raw or "<%s" in raw.replace(" ", "")),
        redirect_stderr=redirect_stderr,
        filecheck_args=filecheck_args,
        line_index=line_index,
        output=output,
    )


def parse_all_runs(text: str) -> list[ParsedRun]:
    """Parse all supported RUN lines; unsupported ones are omitted."""
    out: list[ParsedRun] = []
    for idx, (_lineno, body) in enumerate(join_run_lines(text)):
        parsed = parse_run_body(body, line_index=idx)
        if parsed is not None:
            out.append(parsed)
    return out


def strip_lit_if_wrapper(body: str) -> str:
    """Strip ``%if feature %{ ... %}`` so the inner RUN can be parsed."""
    raw = body.strip()
    m = _IF_WRAP.match(raw)
    return m.group(1).strip() if m else raw


def run_shape(parsed: ParsedRun, suffix: str) -> RunShape:
    """Classify a supported RUN into a coarse shape used for style matching."""
    if parsed.tool == "opt":
        return "opt"
    argv = " ".join(parsed.argv)
    if suffix == "mir" or any(
        a.startswith(("-run-pass", "-start-before", "-start-after"))
        or a in ("-run-pass", "-start-before", "-start-after")
        for a in parsed.argv
    ) or "-run-pass=" in argv or "-start-before=" in argv or "-start-after=" in argv:
        return "mir_pass"
    if any(
        a.startswith(("-stop-after", "-stop-before", "-print-after", "-print-before"))
        for a in parsed.argv
    ):
        return "llc_partial"
    if parsed.tool == "llc":
        return "llc_codegen"
    return "other"


def triple_from_argv(argv: list[str]) -> str | None:
    """Extract ``-mtriple`` from a parsed RUN argv list."""
    for i, arg in enumerate(argv):
        if arg.startswith("-mtriple="):
            return arg.split("=", 1)[1] or None
        if arg == "-mtriple" and i + 1 < len(argv):
            return argv[i + 1]
    return None


def flags_from_argv(argv: list[str]) -> list[str]:
    """Flags from argv excluding ``-mtriple`` (and its value)."""
    out: list[str] = []
    i = 0
    while i < len(argv):
        arg = argv[i]
        if arg.startswith("-mtriple="):
            i += 1
            continue
        if arg == "-mtriple":
            i += 2
            continue
        out.append(arg)
        i += 1
    return out


def parse_first_run_for_check_line(test_text: str) -> tuple[ToolName, list[str], str]:
    """Compatibility helper for check-line: first RUN → tool, argv, IR/MIR body.

    Matches the previous ``check_line.parse_run_line`` contract used by fill-line
    outputs (``opt|llc … %s -o /dev/null``).
    """
    joined = join_run_lines(test_text)
    if not joined:
        raise ValueError("test has no RUN: line")
    body = joined[0][1]
    # Prefer full grammar; fall back to loose parse for fill-line bare RUN lines.
    parsed = parse_run_body(body, line_index=0)
    if parsed is None:
        # Loose: allow first token opt/llc and strip %s / -o /dev/null.
        tokens = shlex.split(body.split("|", 1)[0].strip())
        if not tokens or tokens[0] not in ("opt", "llc"):
            raise ValueError(f"unsupported tool in RUN: {tokens[0]!r}" if tokens else "empty RUN")
        tool = tokens[0]
        argv: list[str] = []
        i = 1
        while i < len(tokens):
            tok = tokens[i]
            if tok in ("%s", "<"):
                i += 1
                continue
            if tok in ("-o", "--o"):
                i += 2
                continue
            if tok.startswith("-o=") or tok.startswith("--o="):
                i += 1
                continue
            if tok == "/dev/null":
                i += 1
                continue
            argv.append(tok)
            i += 1
        argv = [a for a in argv if a != "%s"]
    else:
        tool = parsed.tool
        argv = list(parsed.argv)

    lines = test_text.splitlines()
    start = 0
    for i, line in enumerate(lines):
        stripped = line.strip()
        if stripped.startswith((";", "#")) or stripped == "":
            start = i + 1
            continue
        break
    input_text = "\n".join(lines[start:])
    if input_text and not input_text.endswith("\n"):
        input_text += "\n"
    return tool, argv, input_text  # type: ignore[return-value]


def autogen_script(text: str) -> str | None:
    """Return the update script basename from the NOTE line, if any."""
    m = _NOTE_RE.search(text)
    if not m:
        return None
    name = Path(m.group(1)).name
    return name


def split_ll_functions(text: str) -> list[LitFunction]:
    """Split an ``.ll`` file into functions with preceding CHECK blocks."""
    lines = text.splitlines()
    # Find define lines.
    defines: list[tuple[int, str]] = []
    for i, line in enumerate(lines):
        if line.lstrip().startswith("define ") or line.startswith("define "):
            m = re.search(r"@([A-Za-z0-9_.$]+)\s*\(", line)
            if m:
                defines.append((i, m.group(1)))
    if not defines:
        return []

    funcs: list[LitFunction] = []
    for idx, (def_i, name) in enumerate(defines):
        end = defines[idx + 1][0] if idx + 1 < len(defines) else len(lines)
        # Walk back over CHECK / blank / attribute comment lines for checks.
        start = def_i
        j = def_i - 1
        while j >= 0:
            s = lines[j].strip()
            if s == "" or _CHECK_LINE.match(lines[j]) or s.startswith(";"):
                # Stop at another define's territory: blank after previous body is ok
                if s.startswith("define "):
                    break
                start = j
                j -= 1
                continue
            break
        # Don't steal previous function's body: start at least after previous end
        if idx > 0:
            prev_end = funcs[-1].end if funcs else 0
            # previous function ends at def_i of this one in our scheme below
            pass
        check_lines = [
            lines[k]
            for k in range(start, def_i)
            if _CHECK_LINE.match(lines[k])
        ]
        body_lines = lines[def_i:end]
        # Trim trailing blank / next-function checks belonging to next: end is next define
        funcs.append(
            LitFunction(
                name=name,
                start=start,
                define_line=def_i,
                end=end,
                check_lines=check_lines,
                body_lines=body_lines,
            )
        )
    # Fix starts so they don't overlap previous body, then clip each end to
    # the next function's check-block start so body_lines exclude the next CHECKs.
    for idx in range(1, len(funcs)):
        prev = funcs[idx - 1]
        cur = funcs[idx]
        if cur.start < prev.define_line + 1:
            cur.start = max(cur.start, prev.define_line)
        cur.check_lines = [
            lines[k]
            for k in range(cur.start, cur.define_line)
            if _CHECK_LINE.match(lines[k])
        ]
    for idx in range(len(funcs) - 1):
        funcs[idx].end = funcs[idx + 1].start
        funcs[idx].body_lines = lines[funcs[idx].define_line : funcs[idx].end]
    return funcs


def function_check_map(text: str) -> dict[str, str]:
    """Map function name → joined CHECK lines (for compare after update)."""
    return {f.name: "\n".join(f.check_lines) for f in split_ll_functions(text)}


def run_lines_text(text: str) -> list[str]:
    return [body for _, body in join_run_lines(text)]


def policy_diff(
    original: str,
    edited: str,
    *,
    new_function: str | None = None,
    allow_new_run: bool = False,
) -> PolicyDiffResult:
    """Reject edits outside the new function / its checks / allowed RUN add."""
    orig_runs = run_lines_text(original)
    edit_runs = run_lines_text(edited)
    run_changed = orig_runs != edit_runs
    if run_changed and not allow_new_run:
        # Allow identical set; if only appended RUN with reason, caller sets allow_new_run
        if len(edit_runs) > len(orig_runs) and edit_runs[: len(orig_runs)] == orig_runs:
            if not allow_new_run:
                return PolicyDiffResult(
                    ok=False,
                    reason="new RUN line requires new_run_line_reason",
                    run_lines_changed=True,
                )
        elif orig_runs != edit_runs:
            return PolicyDiffResult(
                ok=False,
                reason="existing RUN lines must not change",
                run_lines_changed=True,
            )

    orig_fn = function_check_map(original)
    edit_fn = function_check_map(edited)
    changed: list[str] = []
    for name, checks in edit_fn.items():
        if name not in orig_fn:
            if new_function and name != new_function:
                changed.append(name)
            continue
        if orig_fn[name] != checks:
            # Body change of existing function checks
            if new_function and name == new_function:
                continue
            changed.append(name)
        # Also detect body IR changes for existing functions
    orig_bodies = {f.name: "\n".join(f.body_lines) for f in split_ll_functions(original)}
    edit_bodies = {f.name: "\n".join(f.body_lines) for f in split_ll_functions(edited)}
    for name, body in edit_bodies.items():
        if name in orig_bodies and orig_bodies[name] != body:
            if new_function and name == new_function:
                continue
            if name not in changed:
                changed.append(name)

    # Removed functions
    for name in orig_fn:
        if name not in edit_fn:
            changed.append(name)

    if changed:
        return PolicyDiffResult(
            ok=False,
            reason=f"edits outside new function: {changed}",
            changed_functions=changed,
            run_lines_changed=run_changed,
        )

    # New function must exist when claimed
    if new_function and new_function not in edit_bodies:
        return PolicyDiffResult(
            ok=False,
            reason=f"new function {new_function!r} not found in edited file",
        )

    return PolicyDiffResult(ok=True, run_lines_changed=run_changed)


def unified_diff(a: str, b: str, *, fromfile: str = "a", tofile: str = "b") -> str:
    return "".join(
        difflib.unified_diff(
            a.splitlines(keepends=True),
            b.splitlines(keepends=True),
            fromfile=fromfile,
            tofile=tofile,
        )
    )


def extract_function_ir(text: str, name: str) -> str | None:
    """Return the ``define`` … body for ``name``, or None."""
    for f in split_ll_functions(text):
        if f.name == name:
            return "\n".join(f.body_lines)
    return None


def strip_header_comments_keep_run(text: str) -> tuple[list[str], str]:
    """Split leading comment/RUN header from IR body (fill-line style)."""
    lines = text.splitlines()
    header: list[str] = []
    start = 0
    for i, line in enumerate(lines):
        stripped = line.strip()
        if stripped.startswith((";", "#")) or stripped == "":
            header.append(line)
            start = i + 1
            continue
        break
    body = "\n".join(lines[start:])
    if body and not body.endswith("\n"):
        body += "\n"
    return header, body


_AT_NAME = re.compile(r"@([A-Za-z0-9_.$]+)")
_DEFINE_NAME = re.compile(
    r"^\s*define\b[^\n]*?@([A-Za-z0-9_.$]+)\s*\(",
)


@dataclass
class SpliceResult:
    ok: bool
    text: str = ""
    reason: str | None = None
    new_function: str | None = None
    insert_line: int | None = None  # 1-based


def function_name_from_ir(function_ir: str) -> str | None:
    """Return the ``@name`` from a ``define`` block, or None."""
    for line in function_ir.splitlines():
        m = _DEFINE_NAME.match(line)
        if m:
            return m.group(1)
    return None


def _brace_end(lines: list[str], define_i: int) -> int:
    """Exclusive end index of a define body starting at *define_i* (brace depth)."""
    depth = 0
    started = False
    for i in range(define_i, len(lines)):
        for ch in lines[i]:
            if ch == "{":
                depth += 1
                started = True
            elif ch == "}":
                depth -= 1
                if started and depth == 0:
                    return i + 1
    return len(lines)


def list_define_spans(text: str) -> list[tuple[str, int, int]]:
    """Return ``(name, define_line, end_exclusive)`` using brace matching."""
    lines = text.splitlines()
    out: list[tuple[str, int, int]] = []
    for i, line in enumerate(lines):
        m = _DEFINE_NAME.match(line)
        if not m:
            continue
        out.append((m.group(1), i, _brace_end(lines, i)))
    return out


def host_defined_names(text: str) -> set[str]:
    return {name for name, _a, _b in list_define_spans(text)}


def host_global_names(text: str) -> set[str]:
    """Module-level ``@name`` globals / declares (excludes bodies of defines)."""
    lines = text.splitlines()
    covered: set[int] = set()
    for _name, start, end in list_define_spans(text):
        covered.update(range(start, end))
    names: set[str] = set()
    for i, line in enumerate(lines):
        if i in covered:
            continue
        stripped = line.lstrip()
        if stripped.startswith("@"):
            m = _AT_NAME.match(stripped)
            if m:
                names.add(m.group(1))
        elif stripped.startswith("declare "):
            m = _AT_NAME.search(line)
            if m:
                names.add(m.group(1))
    return names


def _named_symbols_in_snippet(snippet: str) -> set[str]:
    return set(_AT_NAME.findall(snippet))


def _module_decl_insert_index(lines: list[str]) -> int:
    """Line index to insert module decls: just before the first define."""
    for i, line in enumerate(lines):
        if _DEFINE_NAME.match(line):
            # Back up over blank lines so decls sit with other module content.
            j = i
            while j > 0 and lines[j - 1].strip() == "":
                j -= 1
            return j
    return len(lines)


def _function_insert_index(
    lines: list[str],
    spans: list[tuple[str, int, int]],
    insert_at: str | dict[str, str],
) -> tuple[int | None, str | None]:
    """Return ``(index, error)`` for where to splice the new function block."""
    if isinstance(insert_at, str):
        kind = insert_at.strip().lower()
        if kind in ("end", ""):
            if not spans:
                return len(lines), None
            return spans[-1][2], None
        return None, f"insert_at string must be 'end', got {insert_at!r}"
    if not isinstance(insert_at, dict):
        return None, "insert_at must be 'end' or {after|before: name}"
    if "after" in insert_at:
        name = str(insert_at["after"])
        for n, _d, end in spans:
            if n == name:
                return end, None
        return None, f"anchor function not found: {name!r}"
    if "before" in insert_at:
        name = str(insert_at["before"])
        for n, define_i, _e in spans:
            if n == name:
                j = define_i
                while j > 0 and lines[j - 1].strip() == "":
                    j -= 1
                # Include a preceding CHECK-only block when CHECKs sit above define.
                k = j
                while k > 0 and (
                    _CHECK_LINE.match(lines[k - 1])
                    or lines[k - 1].strip() == ""
                ):
                    k -= 1
                if k < j and any(_CHECK_LINE.match(lines[t]) for t in range(k, j)):
                    return k, None
                return j, None
        return None, f"anchor function not found: {name!r}"
    return None, "insert_at must be 'end' or {after|before: name}"


def _normalize_block(text: str) -> list[str]:
    block = text.strip("\n")
    if not block.strip():
        return []
    return block.splitlines()


def splice_ll_case(
    host_text: str,
    *,
    function_ir: str,
    checks: str | None = None,
    module_decls: str | None = None,
    insert_at: str | dict[str, str] = "end",
    new_run_line: str | None = None,
    comment: str = ";",
) -> SpliceResult:
    """Harness-owned insertion of a new case into an ``.ll`` host file.

    The model supplies only the new pieces; this function splices them in so
    existing RUN lines and function bodies stay untouched by construction.
    """
    fn_name = function_name_from_ir(function_ir)
    if not fn_name:
        return SpliceResult(ok=False, reason="function_ir has no define @name")
    if not function_ir.strip().startswith("define") and "\ndefine" not in "\n" + function_ir:
        # Allow leading CHECKs mistakenly put in function_ir — still require a define.
        if "define " not in function_ir:
            return SpliceResult(ok=False, reason="function_ir must contain a define")

    existing_fns = host_defined_names(host_text)
    if fn_name in existing_fns:
        return SpliceResult(
            ok=False,
            reason=f"function @{fn_name} already exists in host file; rename it",
            new_function=fn_name,
        )

    # Clash check for module decls / new globals against host module symbols.
    host_syms = host_global_names(host_text) | existing_fns
    decl_syms = _named_symbols_in_snippet(module_decls or "")
    # Function's own @fn_name is fine; other @names in the define are usually locals refs.
    clash = (decl_syms & host_syms) - {fn_name}
    if clash:
        return SpliceResult(
            ok=False,
            reason=(
                f"module_decls clash with existing host symbols: "
                f"{sorted(clash)}; rename or drop them"
            ),
            new_function=fn_name,
        )

    lines = host_text.splitlines()
    spans = list_define_spans(host_text)
    insert_i, err = _function_insert_index(lines, spans, insert_at)
    if err:
        return SpliceResult(ok=False, reason=err, new_function=fn_name)

    fn_block = _normalize_block(checks or "") + _normalize_block(function_ir)
    if not fn_block:
        return SpliceResult(ok=False, reason="empty function_ir", new_function=fn_name)

    # Ensure a blank line before the new block when inserting after content.
    pieces: list[str] = []
    if insert_i > 0 and insert_i <= len(lines) and lines[insert_i - 1].strip() != "":
        pieces.append("")
    pieces.extend(fn_block)
    if insert_i < len(lines) and (not lines[insert_i : insert_i + 1] or lines[insert_i].strip()):
        if pieces and pieces[-1].strip() != "":
            pieces.append("")

    new_lines = lines[:insert_i] + pieces + lines[insert_i:]

    if module_decls and module_decls.strip():
        decl_block = _normalize_block(module_decls)
        # Recompute insert point in the new text (before first define, which may
        # now be the new function if the file was empty of defines).
        decl_i = _module_decl_insert_index(new_lines)
        # If we are inserting decls and the new function is the first define,
        # decls should land before it — good. Avoid duplicating blank lines.
        if decl_i > 0 and new_lines[decl_i - 1].strip() != "":
            decl_block = [""] + decl_block
        if decl_i < len(new_lines) and new_lines[decl_i].strip() != "":
            decl_block = decl_block + [""]
        new_lines = new_lines[:decl_i] + decl_block + new_lines[decl_i:]

    if new_run_line and new_run_line.strip():
        run_body = new_run_line.strip()
        if run_body.lower().startswith("run:"):
            run_body = run_body.split(":", 1)[1].strip()
        run_line = f"{comment} RUN: {run_body}"
        # Append after the last existing RUN (joined physical start lines).
        last_run_i = -1
        for i, line in enumerate(new_lines):
            if _RUN_START.match(line):
                last_run_i = i
                # Skip continuation lines
                j = i
                body = _RUN_START.match(line).group(1).rstrip()  # type: ignore[union-attr]
                while body.endswith("\\"):
                    j += 1
                    if j >= len(new_lines):
                        break
                    body = re.sub(r"^[;#]\s*", "", new_lines[j]).strip()
                last_run_i = j
        if last_run_i < 0:
            new_lines = [run_line, ""] + new_lines
        else:
            new_lines = (
                new_lines[: last_run_i + 1] + [run_line] + new_lines[last_run_i + 1 :]
            )

    text = "\n".join(new_lines)
    if not text.endswith("\n"):
        text += "\n"

    # Verify existing function bodies unchanged (brace-based).
    before = {n: host_text.splitlines()[d:e] for n, d, e in spans}
    after_spans = list_define_spans(text)
    after = {n: text.splitlines()[d:e] for n, d, e in after_spans}
    for name, body in before.items():
        if after.get(name) != body:
            return SpliceResult(
                ok=False,
                reason=f"internal splice error: function @{name} changed",
                new_function=fn_name,
            )
    if fn_name not in after:
        return SpliceResult(
            ok=False,
            reason=f"internal splice error: @{fn_name} missing after insert",
            new_function=fn_name,
        )

    return SpliceResult(
        ok=True,
        text=text,
        new_function=fn_name,
        insert_line=(insert_i + 1) if insert_i is not None else None,
    )


def pass_hint_from_test(text: str) -> str | None:
    """Extract a pass name from the first supported RUN, if any."""
    runs = parse_all_runs(text)
    if not runs:
        return None
    for arg in runs[0].argv:
        if arg.startswith("-run-pass="):
            return arg.split("=", 1)[1]
        if arg.startswith("-passes="):
            return arg.split("=", 1)[1].split(",")[0].strip() or None
    return None


def filecheckify_coverage_run(test_text: str) -> str:
    """Upgrade a coverage-only RUN (``-o /dev/null``, no FileCheck) for FileCheck.

    Leaves RUNs that already pipe to FileCheck unchanged. Rewrites the first
    supported coverage-style RUN to use ``-o - | FileCheck %s`` so stdout is
    available for CHECKs. Comment style follows the existing RUN line.
    """
    joined = join_run_lines(test_text)
    if not joined:
        return test_text

    lines = test_text.splitlines()
    # Find the first supported coverage RUN (no FileCheck) and rewrite its body.
    for start_1based, body in joined:
        parsed = parse_run_body(body)
        if parsed is None:
            continue
        if parsed.filecheck_args is not None:
            return test_text  # Already FileCheck-ready
        # Rebuild tool half with -o -
        args = " ".join(parsed.argv)
        if parsed.stdin_redirect:
            tool = f"{parsed.tool} {args} < %s".rstrip()
        else:
            tool = f"{parsed.tool} {args} %s".rstrip()
        if parsed.redirect_stderr:
            tool = f"{tool} 2>&1"
        new_body = f"{tool} -o - | FileCheck %s"

        # Replace the (possibly continued) RUN starting at start_1based-1
        i = start_1based - 1
        m = _RUN_START.match(lines[i])
        if not m:
            continue
        comment = ";" if lines[i].lstrip().startswith(";") else "#"
        j = i
        body_acc = m.group(1).rstrip()
        while body_acc.endswith("\\"):
            j += 1
            if j >= len(lines):
                break
            body_acc = body_acc[:-1].rstrip() + " "
            body_acc += re.sub(r"^[;#]\s*", "", lines[j]).strip()
        # Replace lines i..j with a single RUN
        new_line = f"{comment} RUN: {new_body}"
        new_lines = lines[:i] + [new_line] + lines[j + 1 :]
        text = "\n".join(new_lines)
        if not text.endswith("\n"):
            text += "\n"
        return text
    return test_text
